for end, clip, move, rate, trim in SHOTS:
    s, e = snap(start), snap(end)
    start = end
    if clip is None:
        continue
    name = c(clip)
    sec = (fr(e) - fr(s)) / FPS
    d = dur[name]
    rate = min(rate, (d - 0.1) / sec)
    t0 = trim if trim is not None else max(0.05, (d - sec * rate) / 2)
    t0 = min(t0, max(0.0, d - sec * rate - 0.05))
    used.append((name, round(t0, 1)))
    o.append(f'        <Shot name="{name}" src="evac/clips/{name}.mp4" from={{{fr(s)}}} durationInFrames={{{fr(e) - fr(s)}}} trim={{{t0:.2f}}} rate={{{rate:.2f}}} motion="{move}" />')
